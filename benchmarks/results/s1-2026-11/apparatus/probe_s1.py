"""S1 pre-data template gate (the negative control). Renders each history of probe-shapes-s1.json in
arm S0's shape (gnomon's mid-turn messages as role "system") and in arm S1's shape (the same history
through gnomon's own steerAsUser at the build under test, generated by make_probe_shapes.mts), and
reports where the marker MARKER-S1Q ends up in the prompt the model would see.

  python3 -I probe_s1.py <base_url>                live: the lane's POST /apply-template (renders, never
                                                   generates), e.g. http://127.0.0.1:18780
  python3 -I probe_s1.py --offline <props.json>    offline: jinja2 with the chat_template in that props
                                                   file (R1H's lane-props.json); used by the preflight

Last lines, which the chain greps:
  PROBE_SHAPES_SHA=<sha>                 the build whose steerAsUser made the S1 shapes
  STEER_TEMPLATE_GATE=pass|fail|error    pass: every gate case renders as expected, i.e. the marker is
                                         ABSENT under S0's shape and PRESENT under S1's shape for a late
                                         system message (A, B, C), and PRESENT in both for a system
                                         message at index 1 (D, the positive control)
exit 0 when the probe ran (whatever it found), 2 when the lane or the template could not be reached.
"""
import json
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOLS = [{"type": "function", "function": {
    "name": "bash", "description": "Execute a POSIX sh command and return its output.",
    "parameters": {"type": "object", "properties": {"command": {"type": "string"}}, "required": ["command"]}}}]


def live_renderer(base: str):
    def render(messages: list, tools: bool) -> tuple[str | None, str]:
        body = {"messages": messages, **({"tools": TOOLS} if tools else {})}
        req = urllib.request.Request(base + "/apply-template", data=json.dumps(body).encode(), method="POST",
                                     headers={"content-type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r).get("prompt"), ""
        except urllib.error.HTTPError as e:
            return None, f"HTTP {e.code}: {e.read()[:300]!r}"
        except Exception as e:  # noqa: BLE001 - reported, never hidden
            return None, f"{type(e).__name__}: {e}"
    return render


def offline_renderer(props_path: str):
    import jinja2
    from jinja2.sandbox import ImmutableSandboxedEnvironment
    props = json.loads(Path(props_path).read_text())

    def raise_exception(msg):
        raise jinja2.exceptions.TemplateError(msg)

    env = ImmutableSandboxedEnvironment(trim_blocks=True, lstrip_blocks=True, extensions=["jinja2.ext.loopcontrols"])
    env.globals["raise_exception"] = raise_exception
    env.filters["tojson"] = lambda x, ensure_ascii=False, indent=None, separators=None, sort_keys=False: json.dumps(
        x, ensure_ascii=ensure_ascii, indent=indent, separators=separators, sort_keys=sort_keys)
    tpl = env.from_string(props["chat_template"])

    def render(messages: list, tools: bool) -> tuple[str | None, str]:
        try:
            return tpl.render(messages=messages, tools=TOOLS if tools else None, add_generation_prompt=True,
                              bos_token=props.get("bos_token", ""), eos_token=props.get("eos_token", "")), ""
        except Exception as e:  # noqa: BLE001
            return None, f"{type(e).__name__}: {e}"
    return render


def around(prompt: str, needle: str, n: int = 70) -> str:
    i = prompt.find(needle)
    return repr(prompt[max(0, i - n): i + len(needle) + n]) if i >= 0 else "-"


def main() -> int:
    args = sys.argv[1:]
    shapes = json.loads((HERE / "probe-shapes-s1.json").read_text())
    marker = shapes["marker"]
    if args[:1] == ["--offline"] and len(args) == 2:
        where, render = f"offline jinja2, template of {args[1]}", offline_renderer(args[1])
    elif len(args) == 1:
        base = args[0].rstrip("/")
        try:
            with urllib.request.urlopen(base + "/v1/models", timeout=15) as r:
                r.read()
        except Exception as e:  # noqa: BLE001
            print(f"lane unreachable: {type(e).__name__}: {e}")
            print("STEER_TEMPLATE_GATE=error")
            return 2
        where, render = f"live {base}/apply-template", live_renderer(base)
    else:
        sys.exit(__doc__)
    print(f"== S1 template probe {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())} ({where})")
    print(f"shapes: S0 = gnomon's mid-turn messages as role system; S1 = steerAsUser at {shapes['sha']} "
          f"({shapes['generated_by']}); marker {marker}")
    verdict, errors = "pass", 0
    for name, c in shapes["cases"].items():
        seen = {}
        for arm in ("s0", "s1"):
            prompt, err = render(c[arm], c["tools"])
            if prompt is None:
                seen[arm] = None
                errors += 1
                print(f"  {name} [{arm.upper()}]: ERROR {err}")
                continue
            seen[arm] = marker in prompt
            print(f"  {name} [{arm.upper()}]: marker {'PRESENT' if seen[arm] else 'absent'}; prompt {len(prompt)} chars, "
                  f"'<think>' x{prompt.count('<think>')}; around marker: {around(prompt, marker)}")
        want = c["expect"]
        ok = seen.get("s0") == want["s0"] and seen.get("s1") == want["s1"]
        tag = "gate" if c["gate"] else "informational"
        print(f"  -> {name}: {'as expected' if ok else 'NOT as expected'} ({tag}; want S0 "
              f"{'present' if want['s0'] else 'absent'}, S1 {'present' if want['s1'] else 'absent'}): {c['why']}")
        if c["gate"] and not ok:
            verdict = "error" if None in seen.values() else "fail"
    if verdict == "fail":
        print("!!! the template does not treat the two shapes as S1 assumes; the arms would not differ as designed")
    print(f"PROBE_SHAPES_SHA={shapes['sha']}")
    print(f"STEER_TEMPLATE_GATE={verdict}")
    return 2 if errors and verdict == "error" else 0


if __name__ == "__main__":
    sys.exit(main())
