"""P2G41's pre-registered analysis (../PRE-REGISTRATION.md, "Analysis (stated now)") over extract.py's cells.csv.

  python3 -I extract.py && python3 -I summarize.py      -> ../summary-p2g41.txt (also printed)

Validity is P2's rule (p2-2026-11/PRE-REGISTRATION.md "Scoring"): a cell is valid when Harbor recorded a verifier
reward AND the arm made at least one model request that returned usage. A pair is compared only where both arms are
valid. Hidden-test fraction = ctrf passed/tests; a task whose verifier wrote no ctrf (react-lead-form, music-harmony)
has no fraction and drops out of the fraction comparison only. Bootstrap: 10,000 task resamples, seed 20261105.
"""
import csv
import glob
import json
import math
import random
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
B, SEED, MARGIN = 10_000, 20261105, 0.10
ARMS = ("gnomonA41", "gnomonB41", "opencode-v2")
LABEL = {"gnomonA41": "A41", "gnomonB41": "B41", "opencode-v2": "O"}

rows = list(csv.DictReader(open(HERE / "cells.csv")))
cell = {(r["arm"], r["task"]): r for r in rows}
tasks = sorted({r["task"] for r in rows})


def f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def valid(r):
    return r is not None and r["valid"] == "True"


def solved(r):
    return r["solved"] == "True"


def frac(r):
    t, p = f(r.get("tests")), f(r.get("passed"))
    return p / t if t else None


def wilson(k, n, z=1.959964):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


def mcnemar_exact(b, c):
    """Two-sided exact McNemar: binomial(b+c, 1/2) on the discordant pairs."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = sum(math.comb(n, i) for i in range(0, k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def boot(diffs, seed=SEED, b=B):
    rng = random.Random(seed)
    n = len(diffs)
    means = sorted(sum(diffs[rng.randrange(n)] for _ in range(n)) / n for _ in range(b))
    return means[int(0.025 * b)], means[int(0.975 * b) - 1]


def verdict(lo, hi):
    if lo > -MARGIN:
        return "parity shown (lower bound > -0.10)"
    if hi < 0:
        return "trails (interval below 0)"
    return "no difference shown (interval crosses 0; lower bound <= -0.10, so parity is NOT shown)"


def paired(x, y, out, judge=True):
    """x vs y over tasks where both cells are valid."""
    both = [t for t in tasks if valid(cell.get((x, t))) and valid(cell.get((y, t)))]
    xs = [cell[(x, t)] for t in both]
    ys = [cell[(y, t)] for t in both]
    b = sum(1 for a, c in zip(xs, ys) if solved(a) and not solved(c))
    c = sum(1 for a, cc in zip(xs, ys) if solved(cc) and not solved(a))
    p = mcnemar_exact(b, c)
    tell = "cannot tell (< 6 discordant pairs)" if b + c < 6 else ("differ" if p < 0.05 else "no difference shown")
    sd = [int(solved(a)) - int(solved(cc)) for a, cc in zip(xs, ys)]
    slo, shi = boot(sd)
    fr = [(frac(a), frac(cc)) for a, cc in zip(xs, ys)]
    fd = [a - cc for a, cc in fr if a is not None and cc is not None]
    flo, fhi = boot(fd)
    X, Y = LABEL[x], LABEL[y]
    out.append(f"{X} vs {Y} (paired, {len(both)} tasks both valid): solved {sum(map(solved, xs))} vs {sum(map(solved, ys))}; "
               f"discordant {X}-only {b}, {Y}-only {c}; exact McNemar p = {p:.3f} -> {tell}")
    out.append(f"  solve-rate difference {X} - {Y}: {sum(sd)/len(sd):+.3f} [95% bootstrap {slo:+.3f}, {shi:+.3f}] -> {verdict(slo, shi) if judge else ''}")
    out.append(f"  hidden-test fraction {X} - {Y} over {len(fd)} tasks with a ctrf on both: mean {st.mean(fd):+.3f} "
               f"[95% bootstrap {flo:+.3f}, {fhi:+.3f}] ({X} {st.mean(a for a, c in fr if a is not None and c is not None):.3f}, "
               f"{Y} {st.mean(c for a, c in fr if a is not None and c is not None):.3f}) -> {verdict(flo, fhi) if judge else ''}")
    return {"both": both, "b": b, "c": c, "p": p, "solve_ci": (slo, shi), "frac_ci": (flo, fhi), "frac_mean": st.mean(fd)}


def main():
    out = []
    say = out.append
    status = (ROOT / "STATUS.txt").read_text().splitlines()
    done = [l for l in status if "P2G41 DONE" in l]
    say("P2G41 summary (pre-registered analysis, PRE-REGISTRATION.md). Generated by analysis/summarize.py from analysis/cells.csv.")
    say(f"Run: {status[0][:20]} .. {done[-1][:20] if done else 'NOT DONE'}; {done[-1][21:] if done else ''}")
    say("Arms: A41 = gnomon v0.4.1 release defaults; B41 = v0.4.1 + hosted recipe; O = opencode V2. deepseek-v4.1-flash via OpenCode Go, 1,800 s cap, k = 1, 29 tasks.")
    say("")
    say("task                              " + "".join(f"{LABEL[a]:>22s}" for a in ARMS))
    for t in tasks:
        line = f"{t:34s}"
        for a in ARMS:
            r = cell.get((a, t))
            if not valid(r):
                s = "invalid"
            else:
                s = "SOLVED" if solved(r) else ("cap" if r["capped"] == "True" else "wrong")
                s += f" {f(r['agent_exec_s']) or 0:5.0f}s {('%s/%s' % (r['passed'], r['tests'])) if r['tests'] else 'n/a':>6s}"
            line += f"{s:>22s}"
        say(line)
    say("")
    say("Per arm (valid cells; P2's rule):")
    for a in ARMS:
        rs = [cell[(a, t)] for t in tasks if (a, t) in cell]
        v = [r for r in rs if valid(r)]
        k = sum(map(solved, v))
        lo, hi = wilson(k, len(v))
        caps = sum(1 for r in v if r["capped"] == "True")
        spend = sum(f(r["allowance"]) or 0 for r in rs)
        fr = [frac(r) for r in v if frac(r) is not None]
        walls = sorted(f(r["agent_exec_s"]) for r in v if f(r["agent_exec_s"]) is not None)
        say(f"  {LABEL[a]:4s} solved {k}/{len(v)} valid ({k/len(v):.1%}, Wilson 95% {lo:.1%}-{hi:.1%}); apparatus/invalid {len(rs)-len(v)}; "
            f"capped {caps}/{len(v)}; mean reward {st.mean(f(r['reward']) for r in v):.3f}; hidden tests {st.mean(fr):.3f} mean fraction over {len(fr)}; "
            f"agent wall median {st.median(walls):.0f}s; allowance ${spend:.4f} (all cells), "
            + (f"${spend/k:.4f}/solved" if k else "$/solved n/a (0 solved)"))
    say("")
    say("PRIMARY: B41 vs O")
    prim = paired("gnomonB41", "opencode-v2", out)
    say("")
    say("SECONDARY")
    paired("gnomonA41", "opencode-v2", out)
    paired("gnomonB41", "gnomonA41", out, judge=False)  # the recipe effect: interval only, no margin applies
    say("")
    # sensitivity: gnomon's own start failure (risk-scorer-replay: /app not writable -> no .gnomon surface) counted as a loss
    say("Sensitivity (not pre-registered): risk-scorer-replay's two gnomon cells never reached the model because gnomon could not")
    say("create .gnomon/ in the read-only /app (USER nobody); that is gnomon's limitation, not the host's. Counting B41 there as an")
    say("unsolved valid cell (O solved it):")
    sd, fd = [], []
    for t in tasks:
        a, o = cell.get(("gnomonB41", t)), cell.get(("opencode-v2", t))
        if not valid(o):
            continue
        if valid(a):
            sd.append(int(solved(a)) - int(solved(o)))
            if frac(a) is not None and frac(o) is not None:
                fd.append(frac(a) - frac(o))
        elif t == "risk-scorer-replay":
            sd.append(0 - int(solved(o)))
            fd.append(0.4 - frac(o) if frac(o) is not None else None)  # gnomon left the visible 2/5 untouched: tests 2/5 pass on an untouched /app
    fd = [x for x in fd if x is not None]
    lo, hi = boot(sd)
    say(f"  solve-rate B41 - O over {len(sd)} tasks: {sum(sd)/len(sd):+.3f} [95% {lo:+.3f}, {hi:+.3f}] -> {verdict(lo, hi)}")
    lo, hi = boot(fd)
    say(f"  hidden-test fraction over {len(fd)}: {st.mean(fd):+.3f} [95% {lo:+.3f}, {hi:+.3f}] -> {verdict(lo, hi)}")
    say("")
    s_lo, s_hi = prim["solve_ci"]
    f_lo, f_hi = prim["frac_ci"]
    say("NON-INFERIORITY VERDICT (10-point margin, stated before data):")
    say(f"  solve rate: B41 - O 95% interval [{s_lo:+.3f}, {s_hi:+.3f}] -> {verdict(s_lo, s_hi)}")
    say(f"  hidden-test fraction: B41 - O 95% interval [{f_lo:+.3f}, {f_hi:+.3f}] -> {verdict(f_lo, f_hi)}")
    say("  n = 29 at k = 1 has low power for a 10-point margin; reported with its interval, never as 'equal'.")
    say("")
    say("Secondaries: timeouts, $/solved, wall time (valid cells)")
    for a in ARMS:
        v = [cell[(a, t)] for t in tasks if valid(cell.get((a, t)))]
        say(f"  {LABEL[a]:4s} caps {sum(r['capped']=='True' for r in v)}; answered-wrong with >=300 s left "
            f"{sum(1 for r in v if not solved(r) and r['capped']!='True' and (f(r['agent_exec_s']) or 0) <= 1500)}; "
            f"wire requests/cell {st.mean(f(r['w_rows']) for r in v):.0f}; prompt tokens/cell {st.mean(f(r['relay_prompt']) or 0 for r in v)/1e6:.2f}M")
    say("")
    say("Mechanism data from gnomon's own per-call records (#144), valid cells (analysis/time_split.csv, reasoning_by_decile.csv):")
    ts = list(csv.DictReader(open(HERE / "time_split.csv")))
    for a in ARMS:
        v = [r for r in ts if r["arm"] == a and valid(cell.get((a, r["task"])))]
        ex = sum(f(r["exec_s"]) for r in v)
        say(f"  {LABEL[a]:4s} model time {sum(f(r['model_s']) for r in v)/ex:.0%} of agent wall; reasoning tokens/cell "
            f"{st.mean(f(r['reasoning_sum']) or 0 for r in v):,.0f}; median reasoning/call {st.median(f(r['reasoning_med']) or 0 for r in v):.0f}; "
            f"calls > 60 s per cell {st.mean(f(r['calls_over_60s']) or 0 for r in v):.1f}")
    say("")
    say("P2G attempt 1 rows (time-separated, never pooled with the above; gnomon = v0.3.1): gnomon 1/28 valid solved, 21 capped;")
    say("opencode-v2 7/29, 13 capped (p2g-2026-11/runs/g2-k1-*/cell.json).")
    say("")
    say("Addendum 1 (2026-11-06): the six owed invalid cells were re-run alone on the same v0.4.1 release (rerun_p2g41.py,")
    say("$0.73): vf2-speedup-networkx A41/B41, music-harmony B41, bun-sourcemap-leak A41/B41/O; superseded attempts are in")
    say("runs-superseded/. Still invalid: risk-scorer-replay A41 and B41 (gnomon could not start: /app read-only; gnomon's limitation,")
    say("see the sensitivity line above), plus any re-run cell that failed the validity rule again (see the per-task table).")
    say("The pre-addendum summary (re-run cells absent) is kept as summary-p2g41-before-addendum1.txt; its verdict was the same:")
    say("solve rate parity NOT shown, hidden-test fraction parity shown.")
    say("See analysis/REPORT.md for the acid test and the failure root causes.")
    text = "\n".join(out) + "\n"
    (ROOT / "summary-p2g41.txt").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
