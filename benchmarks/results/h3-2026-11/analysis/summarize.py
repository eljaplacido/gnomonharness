"""P2G41's pre-registered analysis (../PRE-REGISTRATION.md, "Analysis (stated now)") over extract.py's cells.csv.

  python3 -I extract.py && python3 -I summarize.py      -> ../summary-h3.txt (also printed)

Validity is P2's rule (p2-2026-11/PRE-REGISTRATION.md "Scoring"): a cell is valid when Harbor recorded a verifier
reward AND the arm made at least one model request that returned usage. A pair is compared only where both arms are
valid. Hidden-test fraction = ctrf passed/tests; a task whose verifier wrote no ctrf (react-lead-form, music-harmony)
has no fraction and drops out of the fraction comparison only. Bootstrap: 10,000 task resamples, seed 20261105.
"""
import csv
import glob
import json
import math
import random
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
B, SEED, MARGIN = 10_000, 20261106, 0.10
ARMS = ("R0", "R1", "R2")
LABEL = {"R0": "R0", "R1": "R1", "R2": "R2"}

rows = list(csv.DictReader(open(HERE / "cells.csv")))
cell = {(r["arm"], r["task"]): r for r in rows}
tasks = sorted({r["task"] for r in rows})


def f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def valid(r):
    return r is not None and r["valid"] == "True"


def solved(r):
    return r["solved"] == "True"


def frac(r):
    t, p = f(r.get("tests")), f(r.get("passed"))
    return p / t if t else None


def wilson(k, n, z=1.959964):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


def mcnemar_exact(b, c):
    """Two-sided exact McNemar: binomial(b+c, 1/2) on the discordant pairs."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = sum(math.comb(n, i) for i in range(0, k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def boot(diffs, seed=SEED, b=B):
    rng = random.Random(seed)
    n = len(diffs)
    means = sorted(sum(diffs[rng.randrange(n)] for _ in range(n)) / n for _ in range(b))
    return means[int(0.025 * b)], means[int(0.975 * b) - 1]


def verdict(lo, hi):
    if lo > -MARGIN:
        return "parity shown (lower bound > -0.10)"
    if hi < 0:
        return "trails (interval below 0)"
    return "no difference shown (interval crosses 0; lower bound <= -0.10, so parity is NOT shown)"


def paired(x, y, out, judge=True):
    """x vs y over tasks where both cells are valid."""
    both = [t for t in tasks if valid(cell.get((x, t))) and valid(cell.get((y, t)))]
    xs = [cell[(x, t)] for t in both]
    ys = [cell[(y, t)] for t in both]
    b = sum(1 for a, c in zip(xs, ys) if solved(a) and not solved(c))
    c = sum(1 for a, cc in zip(xs, ys) if solved(cc) and not solved(a))
    p = mcnemar_exact(b, c)
    tell = "cannot tell (< 6 discordant pairs)" if b + c < 6 else ("differ" if p < 0.05 else "no difference shown")
    sd = [int(solved(a)) - int(solved(cc)) for a, cc in zip(xs, ys)]
    slo, shi = boot(sd)
    fr = [(frac(a), frac(cc)) for a, cc in zip(xs, ys)]
    fd = [a - cc for a, cc in fr if a is not None and cc is not None]
    flo, fhi = boot(fd)
    X, Y = LABEL[x], LABEL[y]
    out.append(f"{X} vs {Y} (paired, {len(both)} tasks both valid): solved {sum(map(solved, xs))} vs {sum(map(solved, ys))}; "
               f"discordant {X}-only {b}, {Y}-only {c}; exact McNemar p = {p:.3f} -> {tell}")
    out.append(f"  solve-rate difference {X} - {Y}: {sum(sd)/len(sd):+.3f} [95% bootstrap {slo:+.3f}, {shi:+.3f}] -> {verdict(slo, shi) if judge else ''}")
    out.append(f"  hidden-test fraction {X} - {Y} over {len(fd)} tasks with a ctrf on both: mean {st.mean(fd):+.3f} "
               f"[95% bootstrap {flo:+.3f}, {fhi:+.3f}] ({X} {st.mean(a for a, c in fr if a is not None and c is not None):.3f}, "
               f"{Y} {st.mean(c for a, c in fr if a is not None and c is not None):.3f}) -> {verdict(flo, fhi) if judge else ''}")
    return {"both": both, "b": b, "c": c, "p": p, "solve_ci": (slo, shi), "frac_ci": (flo, fhi), "frac_mean": st.mean(fd)}



def caps_over(x, y):
    both = [t for t in tasks if valid(cell.get((x, t))) and valid(cell.get((y, t)))]
    cx = sum(cell[(x, t)]["capped"] == "True" for t in both)
    cy = sum(cell[(y, t)]["capped"] == "True" for t in both)
    return both, cx, cy


def main():
    out = []
    say = out.append
    status = (ROOT / "STATUS.txt").read_text().splitlines()
    done = [l for l in status if "H3 DONE" in l]
    say("H3 summary (pre-registered analysis, PRE-REGISTRATION.md). Generated by analysis/summarize.py from analysis/cells.csv.")
    say("Analysis code re-pointed from P2G41's analysis/summarize.py: arm names, seed 20261106 and the comparisons changed.")
    say(f"Run: {status[0][:20]} .. {done[-1][:20] if done else 'NOT DONE'}; {done[-1][21:] if done else ''} (+ Addendum 2 re-run)")
    say("Arms: R0 = v0.4.2 release defaults; R1 = R0 + replay_reasoning; R2 = R0 + full hosted recipe (replay, 1M window, nudge off).")
    say("")
    say("task                              " + "".join(f"{LABEL[a]:>22s}" for a in ARMS))
    for t in tasks:
        line = f"{t:34s}"
        for a in ARMS:
            r = cell.get((a, t))
            if not valid(r):
                s = "invalid"
            else:
                s = "SOLVED" if solved(r) else ("cap" if r["capped"] == "True" else "wrong")
                s += f" {f(r['agent_exec_s']) or 0:5.0f}s {('%s/%s' % (r['passed'], r['tests'])) if r['tests'] else 'n/a':>6s}"
            line += f"{s:>22s}"
        say(line)
    say("")
    say("Per arm (valid cells):")
    for a in ARMS:
        rs = [cell[(a, t)] for t in tasks if (a, t) in cell]
        v = [r for r in rs if valid(r)]
        k = sum(map(solved, v))
        lo, hi = wilson(k, len(v))
        caps = sum(1 for r in v if r["capped"] == "True")
        spend = sum(f(r["allowance"]) or 0 for r in rs)
        fr = [frac(r) for r in v if frac(r) is not None]
        walls = sorted(f(r["agent_exec_s"]) for r in v if f(r["agent_exec_s"]) is not None)
        say(f"  {a} solved {k}/{len(v)} valid ({k/len(v):.1%}, Wilson 95% {lo:.1%}-{hi:.1%}); invalid {len(rs)-len(v)}; "
            f"capped {caps}/{len(v)}; hidden tests {st.mean(fr):.3f} mean fraction over {len(fr)}; "
            f"agent wall median {st.median(walls):.0f}s; allowance ${spend:.4f}, "
            + (f"${spend/k:.4f}/solved" if k else "$/solved n/a"))
    say("")
    say("PRIMARY 1: R1 vs R0 (replay alone)")
    p1 = paired("R1", "R0", out, judge=False)
    both, c1, c0 = caps_over("R1", "R0")
    say(f"  capped over {len(both)} tasks valid in both: R1 {c1}, R0 {c0}; difference {c1 - c0:+d}")
    say("")
    say("PRIMARY 2: R2 vs R1 (the rest of the recipe, given replay)")
    paired("R2", "R1", out, judge=False)
    both2, c2, c1b = caps_over("R2", "R1")
    say(f"  capped over {len(both2)} tasks valid in both: R2 {c2}, R1 {c1b}")
    say("")
    flo, fhi = p1["frac_ci"]
    ok_frac, ok_caps = flo > 0, (c1 - c0) <= 1
    say("DECISION RULE (replay_reasoning on as a default), stated before data:")
    say(f"  (a) 95% bootstrap lower bound of R1 - R0 hidden-test fraction > 0: {flo:+.3f} -> {'MET' if ok_frac else 'NOT MET'}")
    say(f"  (b) capped(R1) - capped(R0) <= 1: {c1 - c0:+d} -> {'MET' if ok_caps else 'NOT MET'}")
    say("  VERDICT: " + ("ADOPT replay as a default" if ok_frac and ok_caps else
        "NOT ADOPTED ON THIS EVIDENCE (failed: " + ", ".join(n for n, ok in (("(a)", ok_frac), ("(b)", ok_caps)) if not ok) +
        "). 'No difference shown' is not 'no effect'."))
    say("")
    say("DESCRIPTIVE (not decision-bearing):")
    p20 = paired("R2", "R0", out, judge=False)
    lo20 = p20["frac_ci"][0]
    if lo20 > 0:
        common = [t for t in tasks if all(valid(cell.get((a, t))) and frac(cell[(a, t)]) is not None for a in ARMS)]
        d10 = [frac(cell[("R1", t)]) - frac(cell[("R0", t)]) for t in common]
        d20 = [frac(cell[("R2", t)]) - frac(cell[("R0", t)]) for t in common]
        rng = random.Random(SEED)
        n = len(common)
        shares = []
        for _ in range(B):
            idx = [rng.randrange(n) for _ in range(n)]
            den = sum(d20[i] for i in idx)
            if den != 0:
                shares.append(sum(d10[i] for i in idx) / den)
        shares.sort()
        say(f"  share of the recipe's gain from replay over {n} tasks: {st.mean(d10)/st.mean(d20):.2f} "
            f"[95% percentile {shares[int(0.025*len(shares))]:.2f}, {shares[int(0.975*len(shares))-1]:.2f}]")
    else:
        say(f"  R2 - R0 lower bound {lo20:+.3f} <= 0: denominator not resolved, share not given (pre-registered).")
    say("")
    say("SENSITIVITY (Addendum 2): R1 - R0 without lake-temp-glm (R0 re-run ~4 h after its partners):")
    keep = [t for t in tasks if t != "lake-temp-glm" and valid(cell.get(("R1", t))) and valid(cell.get(("R0", t)))]
    fd = [frac(cell[("R1", t)]) - frac(cell[("R0", t)]) for t in keep
          if frac(cell[("R1", t)]) is not None and frac(cell[("R0", t)]) is not None]
    lo, hi = boot(fd)
    say(f"  hidden-test fraction over {len(fd)} tasks: {st.mean(fd):+.3f} [95% {lo:+.3f}, {hi:+.3f}]")
    say("")
    say("Reference rows (time-separated, never pooled): P2G41 A41/B41 on v0.4.1, see ../p2g41-2026-11/summary-p2g41.txt.")
    text = "\n".join(out) + "\n"
    (ROOT / "summary-h3.txt").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
