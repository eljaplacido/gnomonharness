/**
 * gnomon-core: `gnomon skill export` — gnomon's skills as Agent Skills.
 *
 * Claude Code, Codex, Cursor and opencode load a skill from a directory
 * holding a `SKILL.md` with YAML front matter (`name`, `description`): the
 * shared layout of https://agentskills.io/specification. gnomon's own skills
 * are `.gnomon/skills/<id>.md` with TOML front matter, which those hosts do
 * not read. This writes each active skill in the shared layout, so the same
 * text reaches the other harnesses gnomon governs.
 *
 * What it is not: a change to the surface. It reads `.gnomon/skills/` and
 * writes elsewhere (default `.claude/skills/`), never into `.gnomon/`; the
 * surface hash is only quoted, in a provenance comment. The copies are not
 * authority and are not loaded by gnomon; the host decides when to use them.
 * Proposed skills (not yet accepted by a person) are never exported.
 *
 * Safety: a `SKILL.md` that is not gnomon's (it lacks the marker below) is
 * never overwritten; it is reported as refused.
 */

import { existsSync, lstatSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { recomputeManifest, type GnomonConfig } from "./config.js";
import { loadSkills, type Skill } from "./skills.js";
import { writeFileIn, writeRootFor } from "./root_fs.js";

export const SKILL_EXPORT_MARKER = "gnomon-skill-export";
export const SKILL_EXPORT_FORMATS = ["skill-md"] as const;
export type SkillExportFormat = (typeof SKILL_EXPORT_FORMATS)[number];
/** Read by Claude Code, and by Cursor and opencode as a compatibility directory. Codex reads `.agents/skills`: `--to`. */
export const SKILL_EXPORT_DEFAULT_DIR = join(".claude", "skills");

export type SkillExportAction = "create" | "update" | "unchanged" | "refuse";

export interface SkillExportItem {
  /** gnomon's skill id (the file stem under .gnomon/skills/). */
  id: string;
  /** The Agent Skills name, which is also the directory. Empty when none could be made. */
  name: string;
  /** The SKILL.md this would write, absolute. */
  file: string;
  action: SkillExportAction;
  /** Why, for a refusal. */
  reason?: string;
}

export interface SkillExportResult {
  dir: string;
  format: SkillExportFormat;
  surface_hash: string;
  written: boolean;
  items: SkillExportItem[];
}

/**
 * An Agent Skills name from a gnomon skill id: lowercase letters, digits and
 * hyphens, 1-64 characters, no leading, trailing or doubled hyphen. Empty
 * when nothing usable is left.
 */
export function agentSkillName(id: string): string {
  return id
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64)
    .replace(/-+$/g, "");
}

/** A single-line YAML double-quoted scalar (JSON strings are valid YAML). */
const yamlString = (s: string): string => JSON.stringify(s.replace(/\s+/g, " ").trim());

/** The SKILL.md text for one skill: YAML front matter, a provenance comment, the skill's text. */
export function renderSkillMd(skill: Skill, name: string, surfaceHash: string): string {
  const description = (skill.description ?? skill.name).replace(/\s+/g, " ").trim().slice(0, 1024) || name;
  const roles = skill.roles?.length ? `; gnomon roles: ${skill.roles.join(", ")}` : "";
  const provenance =
    `<!-- ${SKILL_EXPORT_MARKER}: from .gnomon/skills/${skill.id}.md; surface ${surfaceHash}${roles}. ` +
    `Generated by \`gnomon skill export\`; edits here are overwritten, edit the source. -->`;
  return ["---", `name: ${name}`, `description: ${yamlString(description)}`, "---", "", provenance, "", skill.body.trim(), ""].join("\n");
}

/**
 * Plan (and with `write`, perform) the export. Never throws for one skill's
 * trouble: that skill is `refuse` with a reason and the rest go on.
 */
export function exportSkills(
  config: GnomonConfig,
  opts: { project: string; to?: string; format?: SkillExportFormat; write?: boolean }
): SkillExportResult {
  const format = opts.format ?? "skill-md";
  if (!(SKILL_EXPORT_FORMATS as readonly string[]).includes(format)) {
    throw new Error(`--format is one of ${SKILL_EXPORT_FORMATS.join(", ")} (got "${format}")`);
  }
  const dir = resolve(opts.project, opts.to ?? SKILL_EXPORT_DEFAULT_DIR);
  const surface_hash = recomputeManifest(config.gnomonDir).surface_hash;
  const items: SkillExportItem[] = [];
  const taken = new Map<string, string>();
  for (const skill of loadSkills(config)) {
    const name = agentSkillName(skill.id);
    const file = join(dir, name || "(none)", "SKILL.md");
    const refuse = (reason: string) => items.push({ id: skill.id, name, file, action: "refuse", reason });
    if (!name) {
      refuse(`"${skill.id}" has no letters or digits to make an Agent Skills name from`);
      continue;
    }
    if (taken.has(name)) {
      refuse(`its Agent Skills name "${name}" is already taken by ${taken.get(name)}`);
      continue;
    }
    taken.set(name, skill.id);
    const text = renderSkillMd(skill, name, surface_hash);
    const lst = existsSync(file) ? lstatSync(file) : null;
    if (lst?.isSymbolicLink()) {
      refuse("it is a symlink; not writing through it");
      continue;
    }
    let action: SkillExportAction = "create";
    if (lst) {
      if (!lst.isFile()) {
        refuse("it exists and is not a file");
        continue;
      }
      const current = readFileSync(file, "utf-8");
      if (!current.includes(`<!-- ${SKILL_EXPORT_MARKER}:`)) {
        refuse("a SKILL.md that gnomon did not write is already there; not overwriting it");
        continue;
      }
      action = current === text ? "unchanged" : "update";
    }
    if (opts.write && action !== "unchanged") {
      try {
        // Rooted at the project (or, for a directory outside it, at that directory), so nothing escapes by a symlink in the way.
        writeFileIn(writeRootFor(opts.project, dir), file, text);
      } catch (e) {
        refuse(e instanceof Error ? e.message : String(e));
        continue;
      }
    }
    items.push({ id: skill.id, name, file, action });
  }
  return { dir, format, surface_hash, written: opts.write === true, items };
}
